namespace FirstProgram._5._Operators;

public class Arithmetic
{
    public static void Run()
    {
        const int a = 10;
        const int b = 3;
        
        Console.WriteLine(a + b);
        Console.WriteLine(a - b);
        Console.WriteLine(a * b);
        Console.WriteLine(a / b);
        Console.WriteLine(a % b);
    }
}